def run(command):
    try:
        result = subprocess.run(
            command,
            cwd=ROOT,
            check=False,
            capture_output=True,
            text=True,
        )
    except OSError:
        return ""
    return result.stdout.strip()


def modified_files():
    output = run(["git", "status", "--short", "--untracked-files=all"])
    files = []
    for line in output.splitlines():
        if not line.strip():
            continue
        files.append(line[2:].strip())
    return files or ["None"]


def running_status():
    output = run(["lsof", "-i", ":8502"])
    if "LISTEN" in output:
        return f"Running: {URL}"
    return "Not confirmed"


