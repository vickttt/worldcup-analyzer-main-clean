def compress_context(content):
    lines = content.splitlines()
    if len(lines) <= 200:
        return content

    keep_sections = {
        "# WorldCup Analyzer",
        "## Quick Access",
        "## Project Status",
        "## Current Problems",
        "## Current Conclusions",
        "## Next Step",
        "## GPT Focus",
    }
    result = []
    keep = False
    for line in lines:
        if line.startswith("#"):
            keep = line in keep_sections
        if keep:
            result.append(line)
    return "\n".join(result).strip() + "\n"


def main():
    LATEST_FILE.write_text(build_latest(), encoding="utf-8")
    CONTEXT_FILE.write_text(build_context(), encoding="utf-8")
    print(f"Updated {LATEST_FILE}")
    print(f"Updated {CONTEXT_FILE}")


if __name__ == "__main__":
    main()
